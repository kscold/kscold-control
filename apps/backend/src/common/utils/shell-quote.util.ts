/**
 * 값을 POSIX 셸(sh/bash/zsh) 인자 하나로 안전하게 넘기기 위한 인용 유틸.
 *
 * 값 전체를 작은따옴표로 감싸고, 값 안의 작은따옴표는 `'"'"'` 로 이스케이프한다.
 * (작은따옴표 닫기 → 큰따옴표로 감싼 작은따옴표 → 작은따옴표 다시 열기)
 * 작은따옴표 안에서는 변수 전개·명령 치환·글롭이 일어나지 않으므로 경로에
 * 공백이나 `$`, 백틱, 세미콜론이 섞여도 그대로 전달된다.
 *
 * 참고: `'\''` 로 이스케이프하는 변형도 만들어지는 문자열만 다를 뿐 셸이 해석한
 * 결과는 동일하다(중첩 인용까지 확인함). 구현이 갈라져 있으면 어느 쪽이 맞는지
 * 매번 확인해야 하므로 이 함수 하나로 통일한다.
 */
export function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'"'"'`)}'`;
}
