import { Inject, Injectable, Logger } from '@nestjs/common';
import * as fs from 'fs/promises';
import * as path from 'path';
import type { INginxBlocklistWriter } from '../../domain/repositories/nginx-blocklist.writer';
import {
  NGINX_RUNTIME_REPOSITORY,
  type INginxRuntimeRepository,
} from '../../../nginx/domain/repositories/nginx-runtime.repository';

const NGINX_CONF_DIR = path.resolve(
  __dirname,
  '../../../../../../nginx/conf.d',
);
const BLOCKLIST_FILE = path.join(NGINX_CONF_DIR, 'ip-blocklist.conf');

@Injectable()
export class NginxBlocklistWriterImpl implements INginxBlocklistWriter {
  private readonly logger = new Logger(NginxBlocklistWriterImpl.name);

  constructor(
    @Inject(NGINX_RUNTIME_REPOSITORY)
    private readonly runtime: INginxRuntimeRepository,
  ) {}

  async apply(ips: string[]): Promise<{ reloaded: boolean; output: string }> {
    const content = this.renderConfig(ips);
    await fs.mkdir(NGINX_CONF_DIR, { recursive: true });
    // 다른 이름으로 다 쓴 뒤 바꿔 끼워, nginx -t 가 쓰다 만 파일을 읽지 않게 한다.
    // conf.d 는 폴더째 마운트되어 있어 이름을 바꿔도 컨테이너가 새 파일을 본다. *.conf 만 읽으므로 임시 파일은 무시된다.
    const temp = `${BLOCKLIST_FILE}.${process.pid}.tmp`;
    await fs.writeFile(temp, content, 'utf-8');
    await fs.rename(temp, BLOCKLIST_FILE);

    const test = await this.runtime.testConfig();
    if (!test.success) {
      this.logger.error(`nginx -t failed, skipping reload: ${test.output}`);
      return { reloaded: false, output: test.output };
    }

    const reload = await this.runtime.reload();
    if (!reload.success) {
      this.logger.error(`nginx reload failed: ${reload.output}`);
      return { reloaded: false, output: reload.output };
    }

    this.logger.log(`nginx blocklist applied: ${ips.length} entries`);
    return { reloaded: true, output: reload.output };
  }

  private renderConfig(ips: string[]): string {
    const header = [
      '# Auto-generated by kscold-control SecurityModule.',
      '# Source of truth: ip_bans table. DO NOT EDIT MANUALLY.',
      `# Last sync: ${new Date().toISOString()}`,
      '',
    ].join('\n');

    if (ips.length === 0) {
      return `${header}# (no active bans)\n`;
    }

    const body = ips.map((ip) => `deny ${ip};`).join('\n');
    return `${header}${body}\n`;
  }
}
